#!/usr/bin/env python3
"""Fetch the EdgeTX 128x64 bitmap fonts and write them as a Lua table for the test harness.

The harness (harness.lua) draws text pixel by pixel like a 128x64 EdgeTX radio (RadioMaster Zorro, Boxer,
Pocket, TX12, MT12, X7, X9 Lite). For that it needs EdgeTX's own proportional fonts. EdgeTX is GPLv2 and this
repository is MIT, so the font bitmaps are not committed: this tool downloads them from a pinned EdgeTX release
(or reads them from a local EdgeTX checkout) and writes a cache file outside the repository.

  python3 tools/radio/edgetx/test/edgetx_fonts.py [--edgetx-src DIR] [--out FILE]

Default output: $TMPDIR/openrc_edgetx_fonts.lua (the harness's default path). Python standard library only.
"""
from __future__ import annotations

import argparse
import os
import struct
import sys
import tempfile
import urllib.request
import zlib
from pathlib import Path

TAG = "v2.12.5"
URL = "https://raw.githubusercontent.com/EdgeTX/edgetx/{tag}/radio/src/fonts/std/{name}"
# harness font index: (file, glyph cell width in the strip, band height = rows EdgeTX's encoder reads per glyph,
# rows the glyph draws). Index 0 = standard 5x7, 2 = SMLSIZE 4x6, 3 = MIDSIZE 8x10 (EdgeTX's FONTSIZE(flags) >> 8).
# A strip column whose `band` rows are all black is a spacer that EdgeTX skips (proportional fonts). The standard
# font draws rows 0-6 (row 7 is cleared), SMLSIZE draws rows 0-6 (its 7th encoded row too), MIDSIZE rows 0-11.
FONTS = {
    0: ("font_05x07.png", 5, 8, 7),
    2: ("font_04x06.png", 5, 7, 7),
    3: ("font_08x10.png", 8, 12, 12),
}
FIRST_CHAR, CHAR_COUNT, PER_BAND_MIN = 0x20, 96, 16


def read_png_gray(data: bytes) -> tuple[int, int, list[list[int]]]:
    """Decode a non-interlaced greyscale PNG (bit depth 1 or 8) into rows of 0..255."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos, idat, header = 8, b"", None
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    width, height, depth, color, _, _, interlace = header
    if color != 0 or depth not in (1, 8) or interlace:
        raise ValueError(f"unsupported PNG: colour type {color}, depth {depth}, interlace {interlace}")
    raw = zlib.decompress(idat)
    stride = (width * depth + 7) // 8
    bpp = 1
    rows, prev, i = [], bytearray(stride), 0
    for _ in range(height):
        filt, line = raw[i], bytearray(raw[i + 1:i + 1 + stride])
        i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if filt == 1:
                line[x] = (line[x] + a) & 0xFF
            elif filt == 2:
                line[x] = (line[x] + b) & 0xFF
            elif filt == 3:
                line[x] = (line[x] + (a + b) // 2) & 0xFF
            elif filt == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else (b if pb <= pc else c))) & 0xFF
        prev = line
        if depth == 8:
            rows.append(list(line))
        else:
            rows.append([255 if (line[x // 8] >> (7 - x % 8)) & 1 else 0 for x in range(width)])
    return width, height, rows


def glyphs(png: bytes, cell: int, band: int, used: int) -> list[list[list[int]]]:
    """Per character: the columns EdgeTX keeps (a fully black strip column is a spacer and is dropped),
    each column a list of the pixel rows that are set. Black in the strip = pixel on, as in EdgeTX's encoder."""
    width, height, rows = read_png_gray(png)
    per_band = width // cell
    out = []
    for k in range(CHAR_COUNT):
        top, left = (k // per_band) * band, (k % per_band) * cell
        cols = []
        for x in range(left, left + cell):
            black = [y for y in range(band) if top + y < height and rows[top + y][x] == 0]
            if len(black) == band:  # all black: EdgeTX's "skip this column" marker
                continue
            on = [y for y in black if y < used]
            cols.append(on)
        out.append(cols)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--edgetx-src", type=Path, help="EdgeTX checkout to read radio/src/fonts/std from")
    ap.add_argument("--out", type=Path, default=Path(os.environ.get("TMPDIR", tempfile.gettempdir())) / "openrc_edgetx_fonts.lua")
    args = ap.parse_args()
    lines = [f"-- EdgeTX {TAG} 128x64 fonts (GPLv2, EdgeTX project), generated by edgetx_fonts.py. Not for the repository.",
             "return {"]
    for idx, (name, cell, band, used) in FONTS.items():
        if args.edgetx_src:
            png = (args.edgetx_src / "radio/src/fonts/std" / name).read_bytes()
        else:
            with urllib.request.urlopen(URL.format(tag=TAG, name=name), timeout=30) as r:
                png = r.read()
        chars = glyphs(png, cell, band, used)
        lines.append(f"  [{idx}] = {{ rows = {used}, chars = {{")
        for k, cols in enumerate(chars):
            body = ",".join("{" + ",".join(map(str, c)) + "}" for c in cols)
            lines.append(f"    [{FIRST_CHAR + k}] = {{{body}}},")
        lines.append("  } },")
    lines.append("}")
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
