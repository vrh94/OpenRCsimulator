-- Headless test harness for the OpenRC EdgeTX scripts (tools/radio/edgetx/SCRIPTS). It runs a script under a desktop
-- Lua (5.2 or newer) against a mock of the EdgeTX 2.12 Lua API for a 128x64 radio: lcd calls are recorded and checked
-- against the screen, sensors come from a scenario table, files live under a temporary SD root, and serialRead/Write
-- use in-memory FIFOs. Run: lua tools/radio/edgetx/test/test_flight.lua [path/to/SOUNDS/en]
local H = {}

H.W, H.H = 128, 64
H.failures = 0

function H.check(label, ok, detail)
  if ok then print("ok   " .. label) else
    H.failures = H.failures + 1
    print("FAIL " .. label .. (detail and (" " .. tostring(detail)) or ""))
  end
end

-- Lua 5.2 had math.atan2; EdgeTX keeps it.
if not math.atan2 then math.atan2 = function(y, x) return math.atan(y, x) end end

-- Flags and constants: the real EdgeTX values for 128x64 radios (gui/common/stdlcd/lcd_common.h). Some share a
-- value on purpose: INVERS == FORCE and RIGHT == ERASE, so a flag passed to the wrong kind of call changes meaning.
BLINK, INVERS, RIGHT, BOLD, PREC1, PREC2, TIMEHOUR = 0x01, 0x02, 0x04, 0x40, 0x20, 0x30, 0x2000
FORCE, ERASE = 0x02, 0x04
TINSIZE, SMLSIZE, MIDSIZE, DBLSIZE, XXLSIZE = 0x0100, 0x0200, 0x0300, 0x0400, 0x0500
SOLID, DOTTED = 0xff, 0x55
EVT_VIRTUAL_NEXT, EVT_VIRTUAL_PREV, EVT_VIRTUAL_ENTER, EVT_VIRTUAL_ENTER_LONG, EVT_VIRTUAL_EXIT = 101, 102, 103, 104, 105
UNIT_GPS = 40

local function bit(v, b) return math.floor(v / b) % 2 == 1 end
local function fontIndex(flags) return math.floor((flags % 0x0800) / 0x0100) end

-- EdgeTX's proportional fonts, generated by edgetx_fonts.py (not committed: EdgeTX is GPLv2). Without the cache the
-- harness falls back to fixed-width cells and says so; pixel-exact checks then only approximate the radio.
H.fontPath = (os.getenv("TMPDIR") or "/tmp") .. "/openrc_edgetx_fonts.lua"
do
  local ok, fonts = pcall(dofile, H.fontPath)
  H.fonts = ok and fonts or nil
end

-- State reset per scenario
function H.reset(scenario)
  H.t = 0
  H.scenario = scenario or {}
  H.sensors = H.scenario.sensors or {}
  H.sources = H.scenario.sources or {}
  H.draws = {}
  H.played = {}
  H.haptics = 0
  H.oob = {}
  H.xor = {}
  H.serialIn = ""
  H.serialOut = {}
  H.telemetry = {}
  H.modelName = H.scenario.model or "SIM"
  H.fb = {}
end

local function problem(list, msg) if #list < 20 then list[#list + 1] = msg end end

local function checkInt(what, ...)
  for _, v in ipairs({ ... }) do
    if type(v) ~= "number" or v ~= math.floor(v) then
      problem(H.oob, what .. ": non-integer coordinate " .. tostring(v) .. " (EdgeTX's Lua rounds or truncates it)")
      return false
    end
  end
  return true
end

-- One pixel of the 1-bit screen. FORCE sets, ERASE clears, anything else XORs (EdgeTX's default for lines,
-- points, rectangles and gauges). A pixel outside the screen is an error here; on the radio it wraps into the
-- neighbouring row or is lost.
local function plot(x, y, att, what)
  if x < 0 or x >= H.W or y < 0 or y >= H.H then
    problem(H.oob, string.format("%s pixel %d,%d off the screen", what, x, y))
    return
  end
  local i = y * H.W + x + 1
  if bit(att, FORCE) then H.fb[i] = 1
  elseif bit(att, ERASE) then H.fb[i] = nil
  else
    -- On a 1-bit screen XOR makes overlapping graphics cancel out; the scripts always pass FORCE or ERASE.
    problem(H.xor, string.format("%s drawn in XOR mode at %d,%d%s", what, x, y, H.fb[i] and " (cleared a pixel)" or ""))
    H.fb[i] = not H.fb[i] and 1 or nil
  end
end

function H.pixel(x, y) return H.fb[y * H.W + x + 1] == 1 end

-- Horizontal and vertical runs with EdgeTX's pattern rules: horizontal patterns rotate per pixel from bit 0;
-- vertical patterns follow the row (y % 8) and DOTTED is inverted when the run starts on an even row.
local function hline(x, y, w, pat, att, what)
  if w < 0 then x = x + w + 1; w = -w end
  for i = 0, w - 1 do
    if pat % 2 == 1 then plot(x + i, y, att, what); pat = math.floor(pat / 2) + 0x80 else pat = math.floor(pat / 2) end
  end
end
local function vline(x, y, h, pat, att, what)
  if h < 0 then y = y + h + 1; h = -h end
  if pat == DOTTED and y % 2 == 0 then pat = 0xff - DOTTED end
  for j = y, y + h - 1 do if bit(pat, 2 ^ (j % 8)) then plot(x, j, att, what) end end
end
local function line(x1, y1, x2, y2, pat, att, what)
  local dx, dy = x2 - x1, y2 - y1
  local adx, ady = math.abs(dx), math.abs(dy)
  local sx, sy = dx > 0 and 1 or (dx < 0 and -1 or 0), dy > 0 and 1 or (dy < 0 and -1 or 0)
  local ex, ey, px, py = math.floor(ady / 2), math.floor(adx / 2), x1, y1
  if adx >= ady then
    for _ = 0, adx do
      if bit(pat, 2 ^ (px % 8)) then plot(px, py, att, what) end
      ey = ey + ady
      if ey >= adx then ey = ey - adx; py = py + sy end
      px = px + sx
    end
  else
    for _ = 0, ady do
      if bit(pat, 2 ^ (py % 8)) then plot(px, py, att, what) end
      ex = ex + adx
      if ex >= ady then ex = ex - ady; px = px + sx end
      py = py + sy
    end
  end
end
local function rect(x, y, w, h, att, what)
  vline(x, y, h, 0xff, att, what)
  vline(x + w - 1, y, h, 0xff, att, what)
  hline(x + 1, y + h - 1, w - 2, 0xff, att, what)
  hline(x + 1, y, w - 2, 0xff, att, what)
end

local function glyph(c, fi)
  if H.fonts and H.fonts[fi] and H.fonts[fi].chars[c] then return H.fonts[fi].chars[c], H.fonts[fi].rows end
  local w = ({ [0] = 5, [2] = 3, [3] = 7 })[fi] or 5
  local cols = {}
  for i = 1, w do cols[i] = { 0, 1, 2, 3, 4, 5 } end
  return cols, ({ [0] = 7, [2] = 7, [3] = 12 })[fi] or 7
end

function H.textWidth(text, flags)
  local w, fi = 0, fontIndex(flags or 0)
  for i = 1, #text do w = w + #glyph(string.byte(text, i), fi) + 1 end
  return w
end

-- Text is opaque, as on the radio: each column of the character cell is set or cleared, plus a cleared spacing
-- column on the right. INVERS adds a filled column on the left and a filled row above. Standard text clears a row
-- under the glyph (8 rows), SMLSIZE fills 7 rows, MIDSIZE 12.
local function drawChar(x, y, c, flags)
  local fi = fontIndex(flags)
  local cols, rows = glyph(c, fi)
  local inv = bit(flags, INVERS)
  local cellRows = (fi == 0) and rows + 1 or rows
  local function column(cx, on)
    if cx < 0 or cx >= H.W then problem(H.oob, string.format("text '%c' column %d off the screen", c, cx)); return end
    local set = {}
    for _, r in ipairs(on) do set[r] = true end
    local top = (inv and rows < 12) and -1 or 0
    for j = top, cellRows - 1 do
      local p = set[j] == true
      if inv then p = not p end
      if y + j >= 0 then plot(cx, y + j, p and FORCE or ERASE, "text") end
    end
  end
  if inv and x > 0 then column(x - 1, {}) end
  for i, on in ipairs(cols) do column(x + i - 1, on) end
  column(x + #cols, {})
  return x + #cols + 1
end

lcd = {}
function lcd.clear() H.draws = {}; H.fb = {} end
function lcd.drawText(x, y, text, flags)
  flags = flags or 0
  text = tostring(text)
  if not checkInt("drawText", x, y) then return end
  local w = H.textWidth(text, flags)
  local x1 = bit(flags, RIGHT) and (x - w) or x
  local fi = fontIndex(flags)
  local _, rows = glyph(65, fi)
  local h = (fi == 0) and rows + 1 or rows
  local inv = bit(flags, INVERS)
  H.draws[#H.draws + 1] = { "text", text, inv and x1 > 0 and x1 - 1 or x1, (inv and rows < 12 and y > 0) and y - 1 or y,
    w + ((inv and x1 > 0) and 1 or 0), h + ((inv and rows < 12 and y > 0) and 1 or 0), flags }
  local cx = x1
  for i = 1, #text do cx = drawChar(cx, y, string.byte(text, i), flags) end
end
function lcd.drawNumber(x, y, v, flags) lcd.drawText(x, y, tostring(math.floor(v)), flags) end
-- lcd.drawTimer: "MM:SS"; RIGHT moves the start left by a fixed 26 px (EdgeTX's 5 * FWNUM + 1), whatever the font.
function lcd.drawTimer(x, y, v, flags)
  flags = flags or 0
  if not checkInt("drawTimer", x, y, v) then return end
  if bit(flags, RIGHT) then
    flags = flags - RIGHT
    x = x - (fontIndex(flags) == 3 and 32 or 26)
  end
  lcd.drawText(x, y, string.format("%02d:%02d", math.floor(v / 60), v % 60), flags)
end
function lcd.drawLine(x1, y1, x2, y2, pattern, flags)
  assert(pattern ~= nil and flags ~= nil, "lcd.drawLine needs pattern and flags on EdgeTX")
  if not checkInt("drawLine", x1, y1, x2, y2) then return end
  if x1 < 0 or y1 < 0 or x2 < 0 or y2 < 0 then
    problem(H.oob, string.format("drawLine negative coordinate %d,%d-%d,%d (EdgeTX reads it as unsigned)", x1, y1, x2, y2))
    return
  end
  H.draws[#H.draws + 1] = { "line", x1, y1, x2, y2, pattern, flags }
  if pattern == SOLID and x1 == x2 then vline(x1, math.min(y1, y2), math.abs(y2 - y1) + 1, 0xff, flags, "line")
  elseif pattern == SOLID and y1 == y2 then hline(math.min(x1, x2), y1, math.abs(x2 - x1) + 1, 0xff, flags, "line")
  else line(x1, y1, x2, y2, pattern, flags, "line") end
end
function lcd.drawPoint(x, y, flags)
  if not checkInt("drawPoint", x, y) then return end
  H.draws[#H.draws + 1] = { "point", x, y, flags or 0 }
  plot(x, y, flags or 0, "point")
end
function lcd.drawRectangle(x, y, w, h, flags)
  if not checkInt("drawRectangle", x, y, w, h) then return end
  H.draws[#H.draws + 1] = { "rect", x, y, w, h, flags or 0 }
  rect(x, y, w, h, flags or 0, "rect")
end
function lcd.drawFilledRectangle(x, y, w, h, flags)
  if not checkInt("drawFilledRectangle", x, y, w, h) then return end
  H.draws[#H.draws + 1] = { "fill", x, y, w, h, flags or 0 }
  for j = y, y + h - 1 do hline(x, j, w, 0xff, flags or 0, "fill") end
end
function lcd.drawGauge(x, y, w, h, fill, max, flags)
  if not checkInt("drawGauge", x, y, w, h, fill, max) then return end
  flags = flags or 0
  H.draws[#H.draws + 1] = { "gauge", x, y, w, h, fill / max, flags }
  rect(x, y, w, h, flags, "gauge")
  local len = math.max(0, math.min(w - 2, math.floor(((w - 2) * fill + math.floor(max / 2)) / max)))
  for j = y + 1, y + h - 2 do hline(x + 1, j, len, 0xff, flags, "gauge") end
end

function getTime() return H.t end
function getRSSI()
  local v = H.scenario.rssi
  if type(v) == "function" then v = v(H.t) end
