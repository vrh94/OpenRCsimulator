H.realIo = realIo

-- Scripts run with only the globals a black-and-white EdgeTX 2.12 radio has (radio/src/thirdparty/Lua/src/linit.c:
-- the table library exists on colour radios only; os, utf8, coroutine, debug and require are never built). Using
-- one fails here as it does on the radio ("attempt to index a nil value (field 'table')").
local MISSING = { table = true, os = true, utf8 = true, coroutine = true, debug = true, require = true, package = true }
H.env = setmetatable({}, {
  __index = function(_, k)
    if MISSING[k] then error("'" .. k .. "' does not exist on a black-and-white EdgeTX radio", 2) end
    return _G[k]
  end,
})

function loadScript(path)
  local local_path = H.scripts .. path
  local f = realIo.open(local_path, "rb")
  if not f then return nil end
  f:close()
  return assert(loadfile(local_path, "t", H.env))
end

function H.load(rel)
  local chunk = assert(loadfile(H.scripts .. rel, "t", H.env))
  return chunk()
end

function H.tick(script, n, event, visible)
  for _ = 1, n do
    H.t = H.t + 3
    if visible then script.run(event or 0); event = 0 else script.background() end
  end
end

-- Writes the current frame's primitives, one per line, for a preview renderer.
function H.dump(path)
  local f = H.realIo.open(path, "wb")
  for _, d in ipairs(H.draws) do
    local parts = {}
    for i, v in ipairs(d) do parts[i] = tostring(v) end
    f:write(table.concat(parts, "\t"), "\n")
  end
  f:close()
end

-- The frame as text art ("#" = pixel on), for failure messages and previews.
function H.art()
  local out = {}
  for y = 0, H.H - 1 do
    local row = {}
    for x = 0, H.W - 1 do row[#row + 1] = H.pixel(x, y) and "#" or "." end
    out[#out + 1] = table.concat(row)
  end
  return table.concat(out, "\n")
end

function H.texts()
  local out = {}
  for _, d in ipairs(H.draws) do if d[1] == "text" then out[#out + 1] = d[2] end end
  return table.concat(out, " | ")
end

function H.overlaps()
  local texts = {}
  for _, d in ipairs(H.draws) do if d[1] == "text" and d[2] ~= "" then texts[#texts + 1] = d end end
  local hits = {}
  for i = 1, #texts do
    for j = i + 1, #texts do
      local a, b = texts[i], texts[j]
      if a[3] < b[3] + b[5] and b[3] < a[3] + a[5] and a[4] < b[4] + b[6] and b[4] < a[4] + a[6] then
        hits[#hits + 1] = "'" .. a[2] .. "' x '" .. b[2] .. "'"
      end
    end
  end
  return hits
end

return H
